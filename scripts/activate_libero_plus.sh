#!/usr/bin/env bash
# Installed into fluxthemis-libero-plus by install_libero_plus.sh.

if [[ "${_FLUXTHEMIS_LIBERO_PLUS_BACKUP_ACTIVE:-0}" != "1" ]]; then
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_PLUS_CONFIG="${LIBERO_PLUS_CONFIG_PATH-}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_PLUS_CONFIG_SET="${LIBERO_PLUS_CONFIG_PATH+x}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_CONFIG_PATH="${LIBERO_CONFIG_PATH-}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_CONFIG_PATH_SET="${LIBERO_CONFIG_PATH+x}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_MUJOCO_GL="${MUJOCO_GL-}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_MUJOCO_GL_SET="${MUJOCO_GL+x}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_PYOPENGL_PLATFORM="${PYOPENGL_PLATFORM-}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_PYOPENGL_PLATFORM_SET="${PYOPENGL_PLATFORM+x}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_EGL_VENDOR="${__EGL_VENDOR_LIBRARY_FILENAMES-}"
  export _FLUXTHEMIS_LIBERO_PLUS_OLD_EGL_VENDOR_SET="${__EGL_VENDOR_LIBRARY_FILENAMES+x}"
  export _FLUXTHEMIS_LIBERO_PLUS_BACKUP_ACTIVE=1
fi

export LIBERO_PLUS_CONFIG_PATH="${LIBERO_PLUS_CONFIG_PATH:-${CONDA_PREFIX}/etc/fluxthemis/libero-plus}"
export LIBERO_CONFIG_PATH="${LIBERO_PLUS_CONFIG_PATH}"
export MUJOCO_GL="${MUJOCO_GL:-egl}"
export PYOPENGL_PLATFORM="${PYOPENGL_PLATFORM:-${MUJOCO_GL}}"

_fluxthemis_nvidia_vendor="${CONDA_PREFIX}/etc/fluxthemis/egl_vendor.d/10_nvidia.json"
if [[ "${MUJOCO_GL}" == "egl" && -z "${__EGL_VENDOR_LIBRARY_FILENAMES:-}" && -f "${_fluxthemis_nvidia_vendor}" ]]; then
  export __EGL_VENDOR_LIBRARY_FILENAMES="${_fluxthemis_nvidia_vendor}"
fi
unset _fluxthemis_nvidia_vendor
